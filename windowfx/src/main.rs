// TQQ WindowFX: one-shot Matugen -> Niri appearance generator.
// No crates, no background service, and no continuous config reload loop.
use std::env;
use std::error::Error;
use std::fs;
use std::io::{self, ErrorKind};
use std::path::{Path, PathBuf};

fn css_color(css: &str, name: &str) -> io::Result<String> {
    for line in css.lines() {
        let mut words = line.split_whitespace();
        if words.next() != Some("@define-color") || words.next() != Some(name) {
            continue;
        }
        let value = words.next().unwrap_or("").trim_end_matches(';');
        let bytes = value.as_bytes();
        if bytes.len() == 7
            && bytes[0] == b'#'
            && bytes[1..].iter().all(u8::is_ascii_hexdigit)
        {
            return Ok(value.to_owned());
        }
        return Err(io::Error::new(
            ErrorKind::InvalidData,
            format!("Invalid Matugen color for {name}: {value}"),
        ));
    }
    Err(io::Error::new(
        ErrorKind::InvalidData,
        format!("Matugen palette is missing color: {name}"),
    ))
}

fn config_dir() -> PathBuf {
    match env::var_os("XDG_CONFIG_HOME") {
        Some(value) if !value.is_empty() => PathBuf::from(value),
        _ => PathBuf::from(env::var_os("HOME").unwrap_or_default()).join(".config"),
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let mut args = env::args_os().skip(1);
    let root = config_dir();
    let palette = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("waybar/colors.css"));
    let destination = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("niri/tqq-windowfx.kdl"));
    if args.next().is_some() {
        return Err("Usage: tqq-windowfx [waybar/colors.css] [niri/tqq-windowfx.kdl]".into());
    }

    let css = fs::read_to_string(&palette)?;
    let primary = css_color(&css, "primary")?;
    let secondary = css_color(&css, "secondary")?;
    let tertiary = css_color(&css, "tertiary")?;
    let error = css_color(&css, "error")?;
    let muted_border = format!("{secondary}55");

    // Niri 26.04 supports includes, gradient borders, geometry clipping,
    // shadows and native compositor animations. Rust only updates the palette.
    let output = format!(
        r##"// GENERATED BY TQQ WindowFX (Rust). Do not edit; changes follow the wallpaper.
// Niri 26.04. No separate daemon or per-frame configuration rewrites.
prefer-no-csd

layout {{
    focus-ring {{
        off
    }}
    border {{
        on
        width 3
        active-gradient from="{primary}" to="{tertiary}" angle=45 in="oklab"
        inactive-color "{muted_border}"
        urgent-color "{error}"
    }}
    shadow {{
        on
        softness 22
        spread 2
        offset x=0 y=5
        color "#00000066"
    }}
    tab-indicator {{
        active-gradient from="{secondary}" to="{tertiary}" angle=45 in="oklab"
    }}
}}

window-rule {{
    geometry-corner-radius 14
    clip-to-geometry true
}}

animations {{
    window-open {{
        duration-ms 230
        curve "ease-out-expo"
    }}
    window-close {{
        duration-ms 175
        curve "ease-out-quad"
    }}
    horizontal-view-movement {{
        spring damping-ratio=0.90 stiffness=600 epsilon=0.0001
    }}
    window-movement {{
        spring damping-ratio=0.90 stiffness=600 epsilon=0.0001
    }}
    window-resize {{
        spring damping-ratio=0.90 stiffness=600 epsilon=0.0001
    }}
    workspace-switch {{
        spring damping-ratio=0.92 stiffness=720 epsilon=0.0001
    }}
}}
"##
    );

    if fs::read_to_string(&destination).ok().as_deref() == Some(output.as_str()) {
        println!("TQQ WindowFX: palette unchanged; Niri config not rewritten.");
        return Ok(());
    }
    let parent = destination.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent)?;
    let tmp = parent.join(format!(".tqq-windowfx-{}.tmp", std::process::id()));
    fs::write(&tmp, output)?;
    if let Err(error) = fs::rename(&tmp, &destination) {
        let _ = fs::remove_file(&tmp);
        return Err(error.into());
    }
    println!("TQQ WindowFX: generated {}", destination.display());
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("TQQ WindowFX: {error}");
        std::process::exit(1);
    }
}
